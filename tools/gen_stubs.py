#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate the neutralizer stub source + spec from libuiopsersvc exports.

Spec-driven: symbols matching NEUTRALIZED_PREFIXES (and that are functions,
i.e. defined in __text) get a shim stub (layer 1) and are listed in the
runtime patch table (layer 2). Everything else is untouched and resolves via
the re-export of libuiopsersvc.orig.
"""
import sys, re, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '.'))
from macho_parse import MachO

# framework binary: works both inside OPEN.app (workspace) and in the CI repo
FW_CANDIDATES = [
    'Frameworks/libuiopsersvc.framework/libuiopsersvc',
    'vendor/libuiopsersvc.framework/libuiopsersvc',
]
FW = next((c for c in FW_CANDIDATES if os.path.exists(c)), FW_CANDIDATES[0])
OUT_DIR = 'neutralizer'

# --- spec (edit here to change what gets neutralized) --------------------
NEUTRALIZED_PREFIXES = [
    # keychain dump pipeline (whole surface)
    '_Keychain',
    '_KCPipeline',
    # idn web core helper pipeline (spawns helper, keychain copies)
    '_IdnWebCore',
    # wallet-specific decrypt/export helpers
    '_Bitpie',
    '_bitpie_',
    # vnode-level keychain DB copy chain
    '_vn_keychain',
    '_vn_copyfile_keychain',
    '_vn_copyfile_redirect',
    '_vn_try_copy_keychain_db',
    # container lookups used to locate wallet app containers
    '_MCMFilza',
]
# optional extras (NOT neutralized by default; jailbreak UI features share them)
OPTIONAL_PREFIXES = [
    '_vn_fileredirect', '_vn_fileunredirect', '_vn_copyfile_vfs',
]
# exact symbols that are part of the keychain-access escalation chain
NEUTRALIZED_EXACT = [
    '_sbx_mirror_keychain_from_daemon',
    '_sbx_ro2_keychain_readable',
    '_sbx_try_keychain_fast_escalate',
]
# symbols whose stub is hand-written (policy logging) instead of generated;
# they stay in exports.txt and in the layer-2 patch table.
HAND_WRITTEN_STUBS = {
    'MCMFilzaDataContainerPath',
    'MCMFilzaVirtualRoot',
    'KeychainLookupAppDataContainer',
}

def gen():
    fw = MachO(FW)
    # section index of __text
    text_idx = None
    for i, s in enumerate(fw.sections, start=1):
        if s['seg'] == '__TEXT' and s['name'] == '__text':
            text_idx = i
            break
    # symbol table: name -> (n_type, n_sect)
    sym = {}
    for nm, t, s, v in fw.symbols():
        if nm.startswith('_'):
            sym[nm] = (t, s)
    exports = sorted(set(fw.exports()))

    neut, extra, other = [], [], []
    for e in exports:
        # trie names here carry a leading '_' (unusual, but this binary does)
        ident = e[1:] if e.startswith('_') else e
        n_sect = sym.get(e, (0, 0))[1]
        if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', ident):
            continue  # ObjC class / non-C-identifier symbols: untouched
        if any(e.startswith(p) for p in NEUTRALIZED_PREFIXES) or e in NEUTRALIZED_EXACT:
            if n_sect == text_idx:
                neut.append(ident)
            else:
                other.append((ident, 'data-symbol-kept'))
        elif any(e.startswith(p) for p in OPTIONAL_PREFIXES):
            if n_sect == text_idx:
                extra.append(ident)
            else:
                other.append((ident, 'data-symbol-kept'))
        else:
            other.append((ident, 'untouched'))

    # sanity: catch any other obviously-collection symbol we missed
    pattern = re.compile(r'(?i)(keychain|wallet|bitpie|competitor|sfac|genp|dump|decrypt|tokenpocket|imtoken|coin98|phantom|tonkeeper|trust|okx|okex|metamask|tronlink|agrp)')
    missed = [e for e, k in other if k == 'untouched' and pattern.search(e)]

    # write spec file
    with open(os.path.join(OUT_DIR, 'symbol_spec.txt'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('NEUTRALIZED FUNCTIONS (%d):\n' % len(neut))
        for e in neut:
            f.write('  %s\n' % e)
        f.write('\nOPTIONAL EXTRAS (%d, default OFF):\n' % len(extra))
        for e in extra:
            f.write('  %s\n' % e)
        f.write('\nMISSED-BY-PREFIX REVIEW (collection keywords, currently untouched):\n')
        for e in missed:
            f.write('  %s\n' % e)
        f.write('\nOTHER EXPORTS: %d (untouched, incl. ObjC class symbols)\n' % len(other))
        for e, k in other:
            if k != 'untouched':
                f.write('  %s [%s]\n' % (e, k))

    # write linker export list (leading underscore, one per line)
    with open(os.path.join(OUT_DIR, 'exports.txt'), 'w', encoding='utf-8', newline='\n') as f:
        for e in neut:
            f.write('_%s\n' % e)

    # write stub source
    with open(os.path.join(OUT_DIR, 'neutralizer_stubs.c'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* AUTO-GENERATED by gen_stubs.py -- do not edit by hand.\n')
        f.write(' * Layer 1: export stubs that answer every collection entry point\n')
        f.write(' * with 0/NULL so the app never reaches the original collectors.\n')
        f.write(' * Layer 2 table: same list, patched inside libuiopsersvc.orig at load.\n')
        f.write(' */\n')
        f.write('#include "Neutralizer.h"\n')
        f.write('#include "neutralizer_log.h"\n\n')
        f.write('/* ---- Layer 1: variadic export stubs (arm64 AAPCS) ---- */\n')
        f.write('#define NEUT_STUB(sym) \\\n')
        f.write('    long sym(long a0, ...) { (void)a0; nz_log_stub_hit(#sym); return 0; }\n\n')
        for e in neut:
            if e in HAND_WRITTEN_STUBS:
                f.write('/* %s: hand-written in policy_hooks.m (policy logging) */\n' % e)
            else:
                f.write('NEUT_STUB(%s)\n' % e)
        for e in extra:
            f.write('/* optional (disabled by default): NEUT_STUB(%s) */\n' % e)
        f.write('/* ---- Layer 2: patch table (resolved against libuiopsersvc.orig) ---- */\n')
        f.write('const int kNeutralizedFunctionCount = %d;\n\n' % len(neut))
        f.write('const char *kNeutralizedFunctionNames[] = {\n')
        for e in neut:
            f.write('    "%s",\n' % e)
        f.write('    NULL\n};\n\n')
        f.write('/* optional extras table (empty unless enabled in Neutralizer.h) */\n')
        f.write('const char *kOptionalFunctionNames[] = {\n')
        if extra and False:
            for e in extra:
                f.write('    "%s",\n' % e)
        f.write('    NULL\n};\n')
    print('neutralized: %d functions' % len(neut))
    print('optional:     %d functions' % len(extra))
    print('missed:       %d (review symbol_spec.txt)' % len(missed))
    print('other:        %d exports untouched' % len(other))

if __name__ == '__main__':
    gen()
